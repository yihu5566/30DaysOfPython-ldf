# 第 1 天 - 30DaysOfPython 挑战

print(2 + 3)             # 加法(+)
print(3 - 1)             # 减法(-)
print(2 * 3)             # 乘法(*)
print(3 / 2)             # 除法(/)
print(3 ** 2)            # 指数(**)
print(3 % 2)             # 取模(%)
print(3 // 2)            # 整除(//)

# 检查数据类型
print(type(10))          # 整数
print(type(3.14))        # 浮点数
print(type(1 + 3j))      # 复数
print(type('Asabeneh'))  # 字符串
print(type([1, 2, 3]))   # 列表
print(type({'name':'Asabeneh'})) # 字典
print(type({9.8, 3.14, 2.7}))    # 集合
print(type((9.8, 3.14, 2.7)))    # 元组
print(type(True))        # 布尔值
print(type(None))        # None
